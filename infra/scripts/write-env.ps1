# Writes .env.azure with the provisioned (non-secret) settings for local
# development against Azure (authenticate with `az login`). See write-env.sh.
$ErrorActionPreference = 'Stop'

$keys = @(
  'AZURE_OPENAI_ENDPOINT', 'AZURE_OPENAI_API_VERSION', 'AZURE_OPENAI_CHAT_DEPLOYMENT',
  'AZURE_OPENAI_EMBEDDING_DEPLOYMENT', 'AZURE_OPENAI_CHAT_REASONING_MODEL', 'AZURE_SPEECH_ENDPOINT',
  'AZURE_SPEECH_REGION', 'COSMOS_ENDPOINT', 'COSMOS_DATABASE_NAME', 'COSMOS_AUDIT_CONTAINER',
  'APPLICATIONINSIGHTS_CONNECTION_STRING'
)
$values = azd env get-values
$lines = @("# Generated by azd postprovision for environment $env:AZURE_ENV_NAME. Contains no secrets.")
foreach ($key in $keys) {
  $lines += $values | Where-Object { $_ -like "$key=*" }
}
$lines += 'APP_ENVIRONMENT=local'
Set-Content -Path '.env.azure' -Value $lines -Encoding utf8
Write-Host "Wrote .env.azure. To run the API locally against Azure: Copy-Item .env.azure .env"
