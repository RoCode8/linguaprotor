#!/bin/sh
# Writes .env.azure with the provisioned (non-secret) settings so the API can be
# run locally against Azure using your own Entra ID credentials (`az login`):
#   cp .env.azure .env && uvicorn src.main:app --reload
set -eu

KEYS="AZURE_OPENAI_ENDPOINT AZURE_OPENAI_API_VERSION AZURE_OPENAI_CHAT_DEPLOYMENT \
AZURE_OPENAI_EMBEDDING_DEPLOYMENT AZURE_OPENAI_CHAT_REASONING_MODEL AZURE_SPEECH_ENDPOINT \
AZURE_SPEECH_REGION COSMOS_ENDPOINT COSMOS_DATABASE_NAME COSMOS_AUDIT_CONTAINER \
APPLICATIONINSIGHTS_CONNECTION_STRING"

OUT=".env.azure"
VALUES="$(azd env get-values)"
{
  echo "# Generated by azd postprovision for environment ${AZURE_ENV_NAME:-?}. Contains no secrets."
  for key in $KEYS; do
    echo "$VALUES" | grep "^${key}=" || true
  done
  echo "APP_ENVIRONMENT=local"
} > "$OUT"
echo "Wrote $OUT. To run the API locally against Azure: cp $OUT .env"
